import { mkdir, mkdtemp, realpath, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import Markdown from 'react-markdown';
import remarkGfm from 'remark-gfm';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

import { exportMarkdown } from '../src/server/actions';
import { config } from '../src/server/config';
import { sideChatPrompt } from '../src/server/side-chat';
import { refreshTranscriptIndex } from '../src/server/transcripts';

// Transcripts written here as Claude Code writes them, in a folder of this test's: nothing of this
// computer's Claude Code is read.
let home: string;
let folder: string;
let project: string;
const saved = { claudeHome: config.claudeHome, env: process.env.CLAUDE_CONFIG_DIR };
const id = (n: number) => `e4e4e4e4-0000-4000-8000-${String(n).padStart(12, '0')}`;

/**
 * A session's rows, each the answer to the one before, as a conversation is on disk; a
 * compaction's boundary starts afresh and points back to what came before it.
 */
async function session(n: number, title: string, rows: Array<Record<string, unknown>>): Promise<string> {
  const sessionId = id(n);
  let parent: string | null = null;
  const lines = [{ type: 'custom-title', customTitle: title, sessionId }, ...rows.map((row, i) => {
    const uuid = `${sessionId.slice(0, 24)}${String(n * 100 + i).padStart(12, '0')}`;
    const links = row.subtype === 'compact_boundary' ? { parentUuid: null, logicalParentUuid: parent } : { parentUuid: parent };
    const line = { uuid, ...links, sessionId, cwd: folder, timestamp: new Date(Date.now() - (100 - i) * 1000).toISOString(), ...row };
    parent = uuid;
    return line;
  })];
  await writeFile(path.join(project, `${sessionId}.jsonl`), `${lines.map((line) => JSON.stringify(line)).join('\n')}\n`);
  await refreshTranscriptIndex();
  return sessionId;
}
const user = (content: unknown, extra: Record<string, unknown> = {}) => ({ type: 'user', message: { role: 'user', content }, ...extra });
const claude = (...content: unknown[]) => ({ type: 'assistant', message: { id: `msg_${crypto.randomUUID().slice(0, 8)}`, type: 'message', role: 'assistant', model: 'claude-opus-5-5', content } });
const text = (value: string) => ({ type: 'text', text: value });
const picture = { type: 'image', source: { type: 'base64', media_type: 'image/png', data: 'iVBORw0KGgo=' } };
/** The export as a Markdown reader takes it, the way the app reads Markdown. */
const read = (markdown: string) => renderToStaticMarkup(createElement(Markdown, { remarkPlugins: [remarkGfm] }, markdown));

beforeAll(async () => {
  // As Claude Code names a project's folder: by the real path (on macOS the temp folder is a link).
  home = await realpath(await mkdtemp(path.join(os.tmpdir(), 'pelican-export-')));
  folder = path.join(home, 'code', 'acme-web');
  await mkdir(folder, { recursive: true });
  config.claudeHome = path.join(home, '.claude');
  process.env.CLAUDE_CONFIG_DIR = config.claudeHome;
  project = path.join(config.claudeHome, 'projects', folder.replace(/[^a-zA-Z0-9]/g, '-'));
  await mkdir(project, { recursive: true });
});
afterAll(async () => {
  config.claudeHome = saved.claudeHome;
  if (saved.env === undefined) delete process.env.CLAUDE_CONFIG_DIR;
  else process.env.CLAUDE_CONFIG_DIR = saved.env;
  await rm(home, { recursive: true, force: true });
});

describe('Export as Markdown', () => {
  it('says what the conversation shows, and leaves out what it leaves out: a side chat’s note, Claude Code’s tags and a compaction’s summary', async () => {
    const upload = path.join(home, 'state', 'uploads', '0a0a0a0a-0000-4000-8000-000000000001', 'chart.png');
    const sessionId = await session(1, 'Side chat', [
      user(sideChatPrompt('Why CSS variables?')),
      claude(text('Let me look.'), { type: 'tool_use', id: 't1', name: 'Read', input: { file_path: `${folder}/src/theme.css` } }),
      user([{ type: 'tool_result', tool_use_id: 't1', content: ':root { --bg: #fff; }' }]),
      claude(text('They switch at once.')),
      user('<bash-input>git status</bash-input>'),
      user('<bash-stdout>On branch main</bash-stdout><bash-stderr></bash-stderr>'),
      user('<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>', { isMeta: true }),
      user('<command-name>/compact</command-name>\n<command-message>compact</command-message>\n<command-args>keep the tests</command-args>'),
      user('<local-command-stdout>Compacted </local-command-stdout>'),
      { type: 'system', subtype: 'compact_boundary' },
      user('This session is being continued from a previous conversation that ran out of context. The theme uses CSS variables.', { isCompactSummary: true }),
      user(`Fix the chart\n\nAttached files:\n- ${upload} (chart.png)`),
      user('Image was scaled down to fit.', { isMeta: true }),
      claude(text('Fixed: the axis starts at zero.')),
      user('[Request interrupted by user]'),
      user('Run `npm test` too\n\n<system-reminder>\nThe user opened src/chart.ts.\n</system-reminder>'),
      claude(text('Done.')),
    ]);
    const { title, markdown } = await exportMarkdown(sessionId);
    expect(title).toBe('Side chat');
    expect(markdown).toBe([
      '# Side chat', '',
      `Folder: \`${folder}\``, '',
      '## You', '',
      'Why CSS variables?', '',
      '## Claude', '',
      'Let me look.', '',
      `- Read: \`${folder}/src/theme.css\``, '',
      'They switch at once.', '',
      '## You', '',
      '`!git status`', '',
      '```\nOn branch main\n```', '',
      '`/compact keep the tests`', '',
      '```\nCompacted\n```', '',
      '*Context compacted*', '',
      '## You', '',
      'Fix the chart', '',
      'Attached: chart.png', '',
      '## Claude', '',
      'Fixed: the axis starts at zero.', '',
      '*Interrupted*', '',
      '## You', '',
      // As the conversation shows it, typed: its backquotes are text.
      'Run \\`npm test\\` too', '',
      '## Claude', '',
      'Done.', '',
    ].join('\n'));
    expect(markdown).not.toMatch(/system-reminder|side chat about|bash-|command-|Caveat|Compacted |continued from|uploads|scaled|interrupted by/);
  });

  it('has what the conversation shows of Claude Code’s own: a / command’s output, a background task, Interrupted, a failed request, a hook’s word', async () => {
    const sessionId = await session(3, 'Notes', [
      user('<command-name>/cost</command-name>\n<command-message>cost</command-message>\n<command-args></command-args>'),
      user('<local-command-stdout>Total cost: $0.12\nTotal duration (API): 1m 2s</local-command-stdout>'),
      user('<task-notification>\n<task-id>b1</task-id>\n<status>completed</status>\n<summary>Background command "npm run build" completed (exit code 0)</summary>\n</task-notification>'),
      claude(text('The build finished.')),
      user('Lint it'),
      claude({ type: 'tool_use', id: 't2', name: 'Bash', input: { command: 'npm run lint' } }),
      user([{ type: 'tool_result', tool_use_id: 't2', content: '2 problems' }]),
      { type: 'attachment', attachment: { type: 'hook_system_message', hookName: 'PostToolUse', content: 'Fix *all* of `src/_x.ts`\n<b>then</b> run [it] again' } },
      claude(text('Fixing both.')),
      user('[Request interrupted by user]'),
      user('Go on'),
      { type: 'assistant', isApiErrorMessage: true, message: { id: 'msg_err', type: 'message', role: 'assistant', model: '<synthetic>', content: [text('API Error: 529 {"type":"error","error":{"type":"overloaded_error","message":"Overloaded"}}')] } },
    ]);
    const { markdown } = await exportMarkdown(sessionId);
    expect(markdown.slice(markdown.indexOf('## You'))).toBe([
      '## You', '',
      '`/cost`', '',
      '```\nTotal cost: $0.12\nTotal duration (API): 1m 2s\n```', '',
      '*Background command "npm run build" completed (exit code 0)*', '',
      '## Claude', '',
      'The build finished.', '',
      '## You', '',
      'Lint it', '',
      '## Claude', '',
      '- Bash: `npm run lint`', '',
      '*PostToolUse says: Fix \\*all\\* of \\`src/\\_x.ts\\`*\n*PostToolUse says: \\<b\\>then\\</b\\> run \\[it\\] again*', '',
      '## Claude', '',
      'Fixing both.', '',
      '*Interrupted*', '',
      '## You', '',
      'Go on', '',
      '*Anthropic\u2019s API is overloaded. Try again in a moment.*', '',
    ].join('\n'));
    // A hook's words are its own: none of them reads as Markdown.
    const html = read(markdown);
    expect(html).toContain('<em>PostToolUse says: Fix *all* of `src/_x.ts`</em>');
    expect(html).toContain('<em>PostToolUse says: &lt;b&gt;then&lt;/b&gt; run [it] again</em>');
  });

  it('names what a prompt carried besides its words: a picture sent alone is there too', async () => {
    const sessionId = await session(4, 'Pictures', [
      user([picture]),
      claude(text('A bar chart.')),
      user([text('And these two'), picture, picture]),
      claude(text('Both line charts.')),
    ]);
    const { markdown } = await exportMarkdown(sessionId);
    expect(markdown.slice(markdown.indexOf('## You'))).toBe([
      '## You', '',
      'Attached: a picture', '',
      '## Claude', '',
      'A bar chart.', '',
      '## You', '',
      'And these two', '',
      'Attached: 2 pictures', '',
      '## Claude', '',
      'Both line charts.', '',
    ].join('\n'));
  });

  it('keeps a command of several lines whole, in a block of code, so none of it reads as Markdown', async () => {
    const sessionId = await session(5, 'Loop', [
      user('<bash-input>for i in 1 2; do\n# a comment\necho $i\n\ndone</bash-input>'),
      user('<bash-stdout>1\n2</bash-stdout><bash-stderr></bash-stderr>'),
      user('<command-name>/compact</command-name>\n<command-message>compact</command-message>\n<command-args>keep the tests\n# and the docs</command-args>'),
      claude({ type: 'tool_use', id: 't3', name: 'Bash', input: { command: 'echo `date`\nls' } }),
    ]);
    const { markdown } = await exportMarkdown(sessionId);
    expect(markdown).toContain([
      '## You', '',
      '```\n!for i in 1 2; do\n# a comment\necho $i\n\ndone\n```', '',
      '```\n1\n2\n```', '',
      '```\n/compact keep the tests\n# and the docs\n```', '',
      '## Claude', '',
      '- Bash: `` echo `date` ``', '',
    ].join('\n'));
    // As a Markdown reader takes it: the title and one heading, and each command and its output as code.
    const html = read(markdown);
    expect(html.match(/<h\d/g)).toEqual(['<h1', '<h2', '<h2']);
    expect(html.match(/<pre>/g)).toHaveLength(3);
  });

  it('keeps a command and its output as code, whatever backticks they hold', async () => {
    const sessionId = await session(2, 'Fences', [
      user('<bash-input>echo `date` ```</bash-input>'),
      user('<bash-stdout>```\nnot the end\n```</bash-stdout><bash-stderr></bash-stderr>'),
    ]);
    const { markdown } = await exportMarkdown(sessionId);
    expect(markdown).toContain('## You\n\n```` !echo `date` ``` ````\n\n````\n```\nnot the end\n```\n````\n');
  });
});

describe('the export, read as the conversation reads', () => {
  /** What a reader shows of some HTML: its text, a line break for each <br>. */
  const textOf = (html: string) => html.replace(/<br\/>\n?/g, '\n').replace(/<[^>]+>/g, '')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#x27;/g, '\'').replace(/&amp;/g, '&');
  /** The speakers' headings and the others, in order, as a reader shows them. */
  const headings = (html: string) => Array.from(html.matchAll(/<(h\d)>(.*?)<\/h\d>/g), (m) => `${m[1]} ${m[2]}`);

  it('reads a prompt as text, as the conversation shows it: none of its Markdown takes effect, and a fence it opens takes nothing after it', async () => {
    const typed = '# Plan\n**bold** and _it_ <b>tag</b> ~~gone~~ [a](b) ![c](d.png) &amp; | x | y |\n- one\n+ two\n1. three\n2) four\n    indented\n\tby a tab\n---\nNext\n===\n```js\nan open fence';
    const sessionId = await session(10, 'Typed', [
      user(typed),
      claude(text('After the fence.')),
      user('And then'),
    ]);
    const { markdown } = await exportMarkdown(sessionId);
    const html = read(markdown);
    // The speakers' headings and nothing else; no list, rule, code, emphasis, link or picture.
    expect(headings(html)).toEqual(['h1 Typed', 'h2 You', 'h2 Claude', 'h2 You']);
    const prompt = html.slice(html.indexOf('<h2>You</h2>') + 12, html.indexOf('<h2>Claude</h2>'));
    expect(prompt).not.toMatch(/<(?:ul|ol|li|hr|pre|code|strong|em|del|a|img|table|b)[ >]/);
    // Its lines as typed, the indented ones still indented, then the reply and the next prompt.
    expect(textOf(prompt).trim()).toBe(typed.replace(/^ {4}/m, '\u00a0'.repeat(4)).replace(/^\t/m, '\u00a0'.repeat(4)));
    expect(html).toContain('<h2>Claude</h2>\n<p>After the fence.</p>\n<h2>You</h2>\n<p>And then</p>');
  });

  it('keeps a quote in a prompt a quote, under where it is from, and what it says text', async () => {
    const sessionId = await session(11, 'Quoted', [
      user('src/app.ts:7-8\n> const a = *b*;\n>   return a;\n\n> # not a heading\n\nWhy?'),
    ]);
    const { markdown } = await exportMarkdown(sessionId);
    const html = read(markdown);
    expect(html).toContain(`<blockquote>\n<p><code>src/app.ts:7-8</code><br/>\nconst a = *b*;<br/>\n${'\u00a0'.repeat(2)}return a;</p>\n</blockquote>`);
    expect(html).toContain('<blockquote>\n<p># not a heading</p>\n</blockquote>\n<p>Why?</p>');
  });

  it('keeps every speaker a speaker: a heading in a prompt or a reply never passes for one', async () => {
    const sessionId = await session(12, 'Headings', [
      user('## Claude\nsays this'),
      claude(text('## You\n\nAll\nYou\n===\n\nOr\n---\n\n# Claude\n\n- ## You\n> ## You\n\n```\n## You\n```\n\n    ## You\n\n###### Deep')),
      user('Thanks'),
    ]);
    const { markdown } = await exportMarkdown(sessionId);
    const html = read(markdown);
    // The reply's headings two levels down, under the speakers'; a heading in code stays code.
    expect(headings(html)).toEqual(['h1 Headings', 'h2 You', 'h2 Claude', 'h4 You', 'h3 All You', 'h4 Or', 'h3 Claude', 'h4 You', 'h4 You', 'h6 Deep', 'h2 You']);
    expect(html.match(/<pre><code>## You\n<\/code><\/pre>/g)).toHaveLength(2);
  });

  it('closes a code block a reply leaves open, so it takes nothing after it, and adds no fence where none is open', async () => {
    const sessionId = await session(13, 'Fences', [
      user('Show me'),
      claude(text('Here:\n\n````js\nconst a = `b`;\n```')),
      user('And a list?'),
      claude(text('- one:\n  ```\n  in the list')),
      user('A quote?'),
      claude(text('> ```\n> in the quote')),
      user('Thanks'),
    ]);
    const { markdown } = await exportMarkdown(sessionId);
    const html = read(markdown);
    expect(headings(html)).toEqual(['h1 Fences', 'h2 You', 'h2 Claude', 'h2 You', 'h2 Claude', 'h2 You', 'h2 Claude', 'h2 You']);
    expect(html).toContain('<pre><code class="language-js">const a = `b`;\n```\n</code></pre>');
    expect(html).toContain('<p>Thanks</p>');
  });

  it('keeps an address or an email text, as the conversation shows them, where a reader would make it a link', async () => {
    const sessionId = await session(14, 'Links', [
      user('Read https://example.com/docs, www.example.org and mail ops@example.com.'),
      claude({ type: 'tool_use', id: 't4', name: 'WebFetch', input: { url: 'https://example.com/docs' } }),
      user([{ type: 'tool_result', tool_use_id: 't4', content: 'Docs' }]),
      { type: 'attachment', attachment: { type: 'hook_system_message', hookName: 'PostToolUse', content: 'See https://hooks.example.com/a?b=1 or www.example.net (ask help@example.com)' } },
      claude(text('Read them.')),
    ]);
    const { markdown } = await exportMarkdown(sessionId);
    const html = read(markdown);
    expect(html).not.toContain('<a ');
    expect(textOf(html)).toContain('Read https://example.com/docs, www.example.org and mail ops@example.com.');
    expect(textOf(html)).toContain('PostToolUse says: See https://hooks.example.com/a?b=1 or www.example.net (ask help@example.com)');
    // The note is still one line in italics.
    expect(html).toContain('<em>PostToolUse says: See <code>https://hooks.example.com/a?b=1</code>');
  });
});

describe('the export, in step with the conversation', () => {
  it('names the computer in a failed request’s line, and says a command failed where the conversation does', async () => {
    const sessionId = await session(9, 'Failures', [
      user('<bash-input>npm test</bash-input>'),
      user('<bash-stdout></bash-stdout><bash-stderr>FAIL theme.test.ts</bash-stderr>', { version: '2.1.318' }),
      // A failed request, as Claude Code writes it: a reply of its own, marked as an API error.
      { type: 'assistant', isApiErrorMessage: true, error: 'unknown', message: { id: 'msg_err', type: 'message', role: 'assistant', model: '<synthetic>', content: [text('API Error: Connection error.')] } },
    ]);
    const { markdown } = await exportMarkdown(sessionId);
    expect(markdown).toContain('```\nFAIL theme.test.ts\n```');
    expect(markdown).toContain('*Failed*');
    expect(markdown).toContain(config.machine);
    expect(markdown).not.toContain('your computer');
  });
});
